/**
 * Builds the consolidated initial migration: the Prisma-generated DDL for the whole schema (`migrate diff --from-empty`) followed by
 * the database guards Prisma cannot express (prisma/sql/*.sql, all idempotent). Output:
 *   prisma/schema/migrations/<MIGRATION_NAME>/migration.sql   (+ migration_lock.toml)
 * (with a multi-file schema folder Prisma keeps the migrations directory INSIDE the schema folder).
 * Re-run whenever a *.prisma file changes before the first deploy; after that add a normal incremental migration instead.
 *   pnpm db:migration:build           (write)
 *   pnpm db:migration:build -- --check (exit 1 when the committed migration no longer matches schema + guards)
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { MIGRATION_SQL_ORDER } from './export-guards';

export const MIGRATION_NAME = '20261015000000_init';
const ROOT = path.resolve(__dirname, '../../..');
const MIG_DIR = path.join(ROOT, 'prisma/schema/migrations');

export function buildMigrationSql(): string {
  const ddl = execFileSync('pnpm', ['exec', 'prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema', '--script'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, env: { ...process.env, DATABASE_URL: process.env.DATABASE_URL ?? 'postgresql://x:x@127.0.0.1:5432/x' } });
  const parts = [`-- SalesOS consolidated initial migration (generated by apps/api/scripts/build-migration.ts). Do not edit by hand.\n-- Part 1: schema DDL from prisma/schema/*.prisma. Part 2: database guards (prisma/sql), all idempotent.\n`, ddl.trim(), ''];
  for (const f of MIGRATION_SQL_ORDER) {
    parts.push(`\n-- ============================================================================\n-- Part 2: prisma/sql/${f}\n-- ============================================================================`);
    parts.push(fs.readFileSync(path.join(ROOT, 'prisma/sql', f), 'utf8').trim());
  }
  return parts.join('\n') + '\n';
}

function main() {
  const file = path.join(MIG_DIR, MIGRATION_NAME, 'migration.sql');
  const sql = buildMigrationSql();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    // The init migration is frozen once it has been deployed (staging databases carry its checksum). Schema changes after that live in
    // incremental migrations, so DDL drift is proven by the later migration-check steps (deploy everything on an empty DB, then
    // `migrate diff` against prisma/schema). Here only the guard SQL (Part 2) must still match prisma/sql/*.sql.
    const part2 = (s: string) => s.slice(s.indexOf('-- Part 2:'));
    if (!current || part2(current) !== part2(sql)) { console.error('prisma/schema/migrations init guards are out of date: run pnpm db:migration:build (before first deploy) or add an incremental migration'); process.exit(1); }
    console.log('init migration guards are up to date (DDL drift is checked by the deploy + diff steps)');
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, sql);
  fs.writeFileSync(path.join(MIG_DIR, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n');
  console.log(`wrote ${path.relative(ROOT, file)} (${sql.split('\n').length} lines)`);
}

if (require.main === module) main();
