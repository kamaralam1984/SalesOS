/**
 * Exports every database guard that Prisma cannot express (immutability triggers, partial unique indexes, analytics indexes) as
 * idempotent SQL files under prisma/sql/, by replaying the same `ensure*Guards` functions the API runs at boot against a
 * recording client. The consolidated migration appends these files, so a database created with `prisma migrate deploy`
 * is identical to one that was booted by the API.
 *   pnpm db:guards:export           (write)
 *   pnpm db:guards:export -- --check (exit 1 when the committed files are out of date)
 */
import fs from 'node:fs';
import path from 'node:path';
import { ensureDbGuards } from '../src/common/prisma/db-guards';
import { ensureRevenueGuards } from '../src/modules/revenue/revenue-guards';
import { ensureSopGuards } from '../src/modules/sop/sop-guards';
import { ANALYTICS_INDEXES } from '../src/modules/reporting/analytics-indexes';

const SQL_DIR = path.resolve(__dirname, '../../../prisma/sql');

/** Hand-written SQL files, applied first and in this order (see MIGRATION_SQL_ORDER). */
export const MIGRATION_SQL_ORDER = ['guards.sql', 'cx-guards.sql', 'revenue-guards.sql', 'sop-guards.sql', 'analytics-indexes.sql'] as const;

function recorder() {
  const sql: string[] = [];
  const client = {
    sql,
    $executeRawUnsafe: async (q: string) => { sql.push(q.trim()); return 0; },
    // "does the trigger exist yet?" -> no, so the CREATE TRIGGER is recorded
    $queryRawUnsafe: async () => [{ n: 0n }],
    $transaction: async (cb: (tx: unknown) => Promise<unknown>) => cb(client),
  };
  return client;
}

/** CREATE TRIGGER is made re-runnable: DROP TRIGGER IF EXISTS precedes it. */
function idempotent(stmt: string): string[] {
  const m = /^CREATE TRIGGER (\w+)\s[\s\S]*?\sON (\w+)\s/i.exec(stmt);
  const body = stmt.endsWith(';') ? stmt : `${stmt};`;
  return m ? [`DROP TRIGGER IF EXISTS ${m[1]} ON ${m[2]};`, body] : [body];
}

function render(title: string, statements: string[]): string {
  const lines = statements.filter((s) => !/^SELECT pg_advisory/i.test(s)).flatMap(idempotent);
  return `-- GENERATED by apps/api/scripts/export-guards.ts (${title}). Do not edit: change the TypeScript guard and re-run \`pnpm db:guards:export\`.\n-- Idempotent: safe to run more than once.\n\n${lines.join('\n\n')}\n`;
}

export async function buildGuardFiles(): Promise<Record<string, string>> {
  const rev = recorder();
  await ensureRevenueGuards(rev as never);
  const sop = recorder();
  await ensureSopGuards(sop as never);
  const base = recorder();
  await ensureDbGuards(base as never);
  const idx = ANALYTICS_INDEXES.map((i) => i.sql);
  return {
    'revenue-guards.sql': render('revenue immutability triggers and forecast snapshot uniqueness', rev.sql),
    'sop-guards.sql': render('SOP version immutability', sop.sql),
    'analytics-indexes.sql': render('analytics query indexes', idx),
    // guards.sql / cx-guards.sql are hand-written (and read by the API at boot); verified for presence only
    '.base-recorded': base.sql.join('\n'),
  };
}

async function main() {
  const files = await buildGuardFiles();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [name, content] of Object.entries(files)) {
    if (name.startsWith('.')) continue;
    const file = path.join(SQL_DIR, name);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (check) {
      if (current !== content) { stale = true; console.error(`prisma/sql/${name} is out of date`); }
    } else {
      fs.writeFileSync(file, content);
      console.log(`wrote prisma/sql/${name}`);
    }
  }
  for (const name of MIGRATION_SQL_ORDER) if (!fs.existsSync(path.join(SQL_DIR, name))) { console.error(`missing prisma/sql/${name}`); stale = true; }
  if (check) {
    if (stale) { console.error('run: pnpm db:guards:export'); process.exit(1); }
    console.log('guard SQL files are up to date');
  }
}

if (require.main === module) void main();
